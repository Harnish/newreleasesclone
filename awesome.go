package main

import (
	"fmt"
	"sort"
	"strings"
)

// buildAwesomeReadme renders a Markdown README of targets. Projects are grouped
// by the user's tags (alphabetical, each with its description; a project with
// several tags is listed under each; untagged ones go last). With no tags at all
// it falls back to grouping by platform. Pure function — no I/O — so output can
// be asserted directly. tags is repoID -> tags; descs is lower-cased tag -> description.
func buildAwesomeReadme(targets []GitLabSyncTarget, tags map[string][]string, descs map[string]string) string {
	var b strings.Builder
	b.WriteString("# Awesome Repos\n\n")
	b.WriteString("Auto-generated by [newreleases](https://github.com/Harnish/newreleases). Do not edit by hand.\n\n")
	if len(targets) == 0 {
		b.WriteString("_No synced repos yet._\n")
		return b.String()
	}

	type group struct {
		title, desc string
		items       []GitLabSyncTarget
	}
	groups := map[string]*group{}
	var untagged []GitLabSyncTarget
	for _, t := range targets {
		if len(tags[t.RepoID]) == 0 {
			untagged = append(untagged, t)
		}
		for _, tag := range tags[t.RepoID] {
			k := strings.ToLower(tag)
			if groups[k] == nil {
				groups[k] = &group{title: tag, desc: descs[k]}
			}
			groups[k].items = append(groups[k].items, t)
		}
	}
	if len(groups) == 0 {
		writeByPlatform(&b, targets)
		return b.String()
	}

	keys := make([]string, 0, len(groups))
	for k := range groups {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		g := groups[k]
		b.WriteString(fmt.Sprintf("## %s\n\n", g.title))
		if g.desc != "" {
			b.WriteString(g.desc + "\n\n")
		}
		writeItems(&b, g.items)
	}
	if len(untagged) > 0 {
		b.WriteString("## Untagged\n\n")
		writeItems(&b, untagged)
	}
	return b.String()
}

func writeItems(b *strings.Builder, items []GitLabSyncTarget) {
	sort.Slice(items, func(i, j int) bool { return items[i].RepoName < items[j].RepoName })
	for _, t := range items {
		b.WriteString(fmt.Sprintf("- [%s](%s)\n", t.RepoName, t.RepoURL))
	}
	b.WriteString("\n")
}

func writeByPlatform(b *strings.Builder, targets []GitLabSyncTarget) {
	groups := map[string][]GitLabSyncTarget{}
	for _, t := range targets {
		groups[t.Platform] = append(groups[t.Platform], t)
	}
	var platforms []string
	for p := range groups {
		platforms = append(platforms, p)
	}
	sort.Strings(platforms)
	for _, p := range platforms {
		b.WriteString(fmt.Sprintf("## %s\n\n", strings.ToUpper(p[:1])+p[1:]))
		writeItems(b, groups[p])
	}
}

// syncAwesomePage regenerates and pushes the Awesome README for userID. A
// no-op returning nil if the user hasn't enabled the feature. A method (not
// a free function reading the global store) for the same reason as
// (*Store).syncProjectToGitLab — see that doc comment.
func (s *Store) syncAwesomePage(userID string) error {
	settings, err := s.GetGitLabSettings(userID)
	if err != nil {
		return err
	}
	if !settings.AwesomeEnabled {
		return nil
	}
	if settings.GitLabToken == "" {
		return fmt.Errorf("gitlab token not configured")
	}
	client := newGitLabClient(settings.GitLabURL, settings.GitLabToken)

	httpURL := settings.AwesomeGitLabPath
	if httpURL == "" {
		name := slugify(settings.AwesomeRepoName)
		path, err := client.PersonalPath(name)
		if err != nil {
			return fmt.Errorf("look up gitlab user: %w", err)
		}
		exists, err := client.ProjectExists(path)
		if err != nil {
			return fmt.Errorf("check awesome project: %w", err)
		}
		if exists {
			httpURL, err = client.GetProjectHTTPURL(path)
		} else {
			httpURL, err = client.CreateProject(0, name)
		}
		if err != nil {
			return fmt.Errorf("create/get awesome project: %w", err)
		}
		if err := s.SetAwesomeGitLabPath(userID, httpURL); err != nil {
			return fmt.Errorf("save awesome project path: %w", err)
		}
	}

	pushURL, err := client.AuthenticatedPushURL(httpURL)
	if err != nil {
		return err
	}
	targets := s.GetUserGitLabSyncTargets(userID)
	content := buildAwesomeReadme(targets, s.GetUserTags(userID), s.GetTagDescriptions(userID))
	return pushGeneratedContent(pushURL, map[string]string{"README.md": content})
}
